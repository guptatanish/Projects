from typing import Literal
from pydantic import BaseModel, Field, field_validator


class ChatRequest(BaseModel):
    """Incoming payload for a chat message."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="User prompt text sent from the chat composer.",
    )

    @field_validator("message")
    @classmethod
    def validate_non_blank_message(cls, value: str) -> str:
        """Reject whitespace-only messages and trim leading/trailing spaces."""
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("Message cannot be empty or whitespace only.")
        return cleaned


class ChatResponse(BaseModel):
    """Standardized response returned after processing a chat message."""

    reply: str = Field(..., description="Assistant response text.")
    role: Literal["assistant"] = Field(
        default="assistant",
        description="Message author role.",
    )
    mode: str = Field(
        default="mock",
        description="Execution mode (e.g. 'mock' in Phase 1, 'gemini_flash' in Phase 2+).",
    )
    model: str | None = Field(
        default=None,
        description="Model identifier when generated by an AI model.",
    )